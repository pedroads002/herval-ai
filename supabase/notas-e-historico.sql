-- recarregamento.
--
-- Por que duas tabelas e não uma: nota é texto que uma pessoa escreveu, e
-- mudança de etapa é um fato que o sistema observou. Guardar as duas coisas na
-- mesma tabela obrigaria metade das colunas a ficar sempre vazia.
--
-- O resto da linha de tempo do lead NÃO ganha tabela, de propósito: a chegada
-- do lead já é `leads.criado_em` e cada fala já é uma linha de `mensagens`.
-- Copiar isso para um terceiro lugar criaria duas versões do mesmo fato.
